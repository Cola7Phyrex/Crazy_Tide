export function resolveNarrativeEntry(
  entry,
  { landName = "初始基本地" } = {},
) {
  const replaceTokens = (text) =>
    text.replaceAll("{{LAND_NAME}}", landName);
  return {
    ...entry,
    title: replaceTokens(entry.title),
    body: replaceTokens(entry.body),
  };
}

